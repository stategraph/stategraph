"use client";

import React, { useState, useRef, useEffect } from "react";
import { Filter, X, Search, Check } from "lucide-react";
import { Button } from "@/components/ui/button";

interface EnhancedFilterBarProps {
  q: string;
  onChange: (q: string) => void;
  providers: string[];
  types: string[];
  modules: string[];
}

export function EnhancedFilterBar({
  q,
  onChange,
  providers: _providers,
  types,
  modules,
}: EnhancedFilterBarProps) {
  // Parse current filters from query string
  const parseFilters = (query: string) => {
    const filters = {
      type: [] as string[],
      module: [] as string[],
    };

    // Split by OR to handle multi-field queries generated by ensureTagQuery
    const orParts = query.split(/\s+OR\s+/);

    orParts.forEach((part) => {
      part.split(/\s+AND\s+|\s+/).forEach((token) => {
        const match = token.trim().match(/^(type|module|address):(.+)$/);
        if (match) {
          const [, key, value] = match;
          if (key === 'type' || key === 'module') {
            if (!filters[key].includes(value)) {
              filters[key].push(value);
            }
          }
        }
      });
    });

    return filters;
  };

  const currentFilters = parseFilters(q);

  // Add a filter
  const addFilter = (key: "type" | "module", value: string) => {
    const updated = { ...currentFilters };
    if (!updated[key].includes(value)) {
      updated[key] = [...updated[key], value];
    }
    buildQueryFromFilters(updated);
  };

  // Remove a filter
  const removeFilter = (key: "type" | "module", value: string) => {
    const updated = { ...currentFilters };
    updated[key] = updated[key].filter((v) => v !== value);
    buildQueryFromFilters(updated);
  };

  // Build query string from filters
  const buildQueryFromFilters = (filters: typeof currentFilters) => {
    const parts: string[] = [];

    filters.type.forEach((v) => parts.push(`type:${v}`));
    filters.module.forEach((v) => parts.push(`module:${v}`));

    onChange(parts.join(" AND "));
  };

  // Clear all filters
  const clearAllFilters = () => {
    onChange("");
  };

  const hasActiveFilters =
    currentFilters.type.length > 0 ||
    currentFilters.module.length > 0;

  const hasAnyOptions = types.length > 0 || modules.length > 0;

  // If no options available, show empty state
  if (!hasAnyOptions) {
    return (
      <div className="px-4 py-8 bg-[var(--sg-bg-2)] border border-[var(--sg-border)] rounded-lg text-center">
        <Filter className="w-8 h-8 text-[var(--sg-text-dim)] mx-auto mb-3" />
        <p className="text-sm text-[var(--sg-text-muted)] mb-1">No resources found in this state</p>
        <p className="text-xs text-[var(--sg-text-dim)]">
          Import a Terraform state file to start searching
        </p>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      {/* Info Banner */}
      <div className="px-4 py-3 bg-[var(--sg-bg-2)] border border-[var(--sg-border)] rounded-lg">
        <div className="flex items-start gap-3">
          <Filter className="w-4 h-4 text-[var(--sg-accent)] mt-0.5 flex-shrink-0" />
          <div className="flex-1">
            <p className="text-sm text-[var(--sg-text)]">
              Build your search query by filtering resource types and modules. Multiple selections within a category are combined with AND.
            </p>
          </div>
        </div>
      </div>

      {/* Filter Controls */}
      <div className="space-y-3">
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {/* Type Filter */}
          <div>
            <label className="block text-sm font-medium text-[var(--sg-text-muted)] mb-2">
              Resource Type
            </label>
            <SearchableFilterDropdown
              options={types}
              selected={currentFilters.type}
              onAdd={(value) => addFilter("type", value)}
              onRemove={(value) => removeFilter("type", value)}
              placeholder="Select type..."
              emptyMessage="No types available"
            />
          </div>

          {/* Module Filter */}
          <div>
            <label className="block text-sm font-medium text-[var(--sg-text-muted)] mb-2">
              Module
            </label>
            <SearchableFilterDropdown
              options={modules}
              selected={currentFilters.module}
              onAdd={(value) => addFilter("module", value)}
              onRemove={(value) => removeFilter("module", value)}
              placeholder="Select module..."
              emptyMessage="No modules available"
            />
          </div>
        </div>

        {/* Clear All Button */}
        {hasActiveFilters && (
          <div className="flex justify-end">
            <Button
              variant="ghost"
              size="sm"
              onClick={clearAllFilters}
              className="text-xs text-[var(--sg-text-dim)] hover:text-[var(--sg-text)]"
            >
              Clear all filters
            </Button>
          </div>
        )}
      </div>

      {/* Active Filter Pills */}
      {hasActiveFilters && (
        <div>
          <div className="text-xs font-medium text-[var(--sg-text-muted)] mb-2">
            Active Filters:
          </div>
          <div className="flex flex-wrap gap-2">
            {currentFilters.type.map((value) => (
              <FilterPill
                key={`type:${value}`}
                label="type"
                value={value}
                onRemove={() => removeFilter("type", value)}
              />
            ))}
            {currentFilters.module.map((value) => (
              <FilterPill
                key={`module:${value}`}
                label="module"
                value={value}
                onRemove={() => removeFilter("module", value)}
              />
            ))}
          </div>
        </div>
      )}

      {/* Generated Query Preview */}
      {hasActiveFilters && (
        <div className="px-4 py-3 bg-[var(--sg-bg-0)] border border-[var(--sg-border)] rounded-lg">
          <div className="text-xs font-medium text-[var(--sg-text-muted)] mb-1">
            Generated Query:
          </div>
          <div className="font-mono text-sm text-[var(--sg-accent)]">
            {q || "(empty)"}
          </div>
        </div>
      )}
    </div>
  );
}

// Searchable Filter Dropdown Component
function SearchableFilterDropdown({
  options,
  selected,
  onAdd,
  onRemove,
  placeholder,
  emptyMessage,
}: {
  options: string[];
  selected: string[];
  onAdd: (value: string) => void;
  onRemove: (value: string) => void;
  placeholder: string;
  emptyMessage: string;
}) {
  const [isOpen, setIsOpen] = useState(false);
  const [searchTerm, setSearchTerm] = useState("");
  const dropdownRef = useRef<HTMLDivElement>(null);
  const searchInputRef = useRef<HTMLInputElement>(null);

  // Close on click outside
  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (
        dropdownRef.current &&
        !dropdownRef.current.contains(event.target as Node)
      ) {
        setIsOpen(false);
        setSearchTerm("");
      }
    };

    if (isOpen) {
      document.addEventListener("mousedown", handleClickOutside);
      return () => document.removeEventListener("mousedown", handleClickOutside);
    }
  }, [isOpen]);

  // Focus search input when dropdown opens
  useEffect(() => {
    if (isOpen && searchInputRef.current) {
      searchInputRef.current.focus();
    }
  }, [isOpen]);

  // Filter options based on search term
  const filteredOptions = options.filter((opt) =>
    opt.toLowerCase().includes(searchTerm.toLowerCase())
  );

  const availableOptions = filteredOptions.filter(
    (opt) => !selected.includes(opt)
  );

  const selectedOptions = filteredOptions.filter((opt) =>
    selected.includes(opt)
  );

  return (
    <div ref={dropdownRef} className="relative">
      {/* Trigger Button */}
      <button
        onClick={() => setIsOpen(!isOpen)}
        className="w-full px-3 py-2 text-sm text-left bg-[var(--sg-bg-2)] border border-[var(--sg-border)] rounded-lg hover:bg-[var(--sg-bg-1)] transition-colors flex items-center justify-between"
      >
        <span className={selected.length === 0 ? "text-[var(--sg-text-dim)]" : ""}>
          {selected.length === 0
            ? placeholder
            : `${selected.length} selected`}
        </span>
        <Search className="w-4 h-4 text-[var(--sg-text-dim)]" />
      </button>

      {/* Dropdown */}
      {isOpen && (
        <div className="absolute top-full mt-1 z-50 w-full bg-[var(--sg-bg-2)] border border-[var(--sg-border)] rounded-lg shadow-lg max-h-80 flex flex-col">
          {/* Search Input */}
          <div className="p-2 border-b border-[var(--sg-border)]">
            <div className="relative">
              <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-[var(--sg-text-dim)]" />
              <input
                ref={searchInputRef}
                type="text"
                value={searchTerm}
                onChange={(e) => setSearchTerm(e.target.value)}
                placeholder="Search..."
                className="w-full pl-9 pr-3 py-2 text-sm bg-[var(--sg-bg-1)] border border-[var(--sg-border)] rounded focus:outline-none focus:border-[var(--sg-accent)]"
              />
            </div>
          </div>

          {/* Options List */}
          <div className="overflow-y-auto flex-1">
            {/* Selected Options */}
            {selectedOptions.length > 0 && (
              <div className="border-b border-[var(--sg-border)]">
                {selectedOptions.map((option) => (
                  <button
                    key={option}
                    onClick={() => onRemove(option)}
                    className="w-full px-3 py-2 text-left text-sm font-mono hover:bg-[var(--sg-bg-1)] transition-colors flex items-center justify-between group"
                  >
                    <span className="text-[var(--sg-accent)]">{option}</span>
                    <Check className="w-4 h-4 text-[var(--sg-accent)]" />
                  </button>
                ))}
              </div>
            )}

            {/* Available Options */}
            {availableOptions.length > 0 ? (
              availableOptions.map((option) => (
                <button
                  key={option}
                  onClick={() => {
                    onAdd(option);
                    setSearchTerm("");
                    setIsOpen(false);
                  }}
                  className="w-full px-3 py-2 text-left text-sm font-mono hover:bg-[var(--sg-bg-1)] transition-colors"
                >
                  {option}
                </button>
              ))
            ) : (
              <div className="px-3 py-8 text-center text-sm text-[var(--sg-text-dim)]">
                {searchTerm
                  ? `No results for "${searchTerm}"`
                  : selected.length === options.length
                  ? "All options selected"
                  : emptyMessage}
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
}

// Filter Pill Component
function FilterPill({
  label,
  value,
  onRemove,
}: {
  label: string;
  value: string;
  onRemove: () => void;
}) {
  return (
    <div className="inline-flex items-center gap-1.5 px-2 py-1 bg-[var(--sg-accent-bg)] border border-[var(--sg-accent)] rounded text-xs">
      <span className="text-[var(--sg-text-dim)]">{label}:</span>
      <span className="font-mono text-[var(--sg-accent)]">{value}</span>
      <button
        onClick={onRemove}
        className="hover:text-[var(--sg-text)] transition-colors"
      >
        <X className="h-3 w-3" />
      </button>
    </div>
  );
}
